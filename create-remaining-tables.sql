-- 2. LIVE MATCH TABLE (Realtime Scoreboard)
CREATE TABLE IF NOT EXISTS public.live_match (
    id BIGINT PRIMARY KEY DEFAULT 1,
    your_team TEXT DEFAULT 'LOVELY FRIENDS' NOT NULL,
    opp_team TEXT DEFAULT 'OPPONENT TEAM' NOT NULL,
    your_score INT DEFAULT 0 NOT NULL,
    opp_score INT DEFAULT 0 NOT NULL,
    timer_seconds INT DEFAULT 1200 NOT NULL,
    is_running INT DEFAULT 0 NOT NULL,
    yt_link TEXT DEFAULT '' NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.live_match ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public read live_match" ON public.live_match;
